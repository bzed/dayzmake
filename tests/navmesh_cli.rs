//! `dayzmake navmesh probe`, `generate` and `info`, driven through the binary against the fake data
//! server and a capture of the synthetic world.
#![cfg_attr(
    unix,
    expect(
        clippy::expect_used,
        clippy::indexing_slicing,
        reason = "a failing expect is a failing test; the shared fake server indexes a checked payload"
    )
)]
// the CLI is run with unix-style environment variables and paths only
#![cfg(unix)]

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use dayzmake::commands::navmesh::{parse_doors, parse_range, parse_seed, parse_tile};
use dayzmake_core::navmesh::build::DoorPolicy;
use dayzmake_core::navmesh::capture::CaptureWriter;
use serde_json::Value;

#[path = "../crates/dayzmake-core/tests/support/navmesh_server.rs"]
mod navmesh_server;
#[path = "../crates/dayzmake-core/tests/support/navmesh_world.rs"]
mod navmesh_world;

use navmesh_server::{FakeServer, Faults};
use navmesh_world::synthetic_world;

struct Env {
    tmp: tempfile::TempDir,
}

struct Out {
    code: i32,
    stdout: String,
    stderr: String,
}

impl Env {
    fn new() -> Env {
        let tmp = tempfile::tempdir().expect("tmp");
        fs::create_dir_all(tmp.path().join("home")).expect("home");
        Env { tmp }
    }

    fn path(&self, name: &str) -> PathBuf {
        self.tmp.path().join(name)
    }

    fn run(&self, args: &[&str]) -> Out {
        let home = self.path("home");
        let out = Command::new(env!("CARGO_BIN_EXE_dayzmake"))
            .args(args)
            .env("HOME", &home)
            .env("XDG_CACHE_HOME", home.join("cache"))
            .env("XDG_CONFIG_HOME", home.join("config"))
            .env("XDG_DATA_HOME", home.join("data"))
            .env("NO_COLOR", "1")
            .current_dir(&home)
            .output()
            .expect("run dayzmake");
        Out {
            code: out.status.code().expect("exit code"),
            stdout: String::from_utf8_lossy(&out.stdout).into_owned(),
            stderr: String::from_utf8_lossy(&out.stderr).into_owned(),
        }
    }

    /// A `.dzgeo` capture of the synthetic world.
    fn capture(&self) -> PathBuf {
        let (params, tiles) = synthetic_world();
        let path = self.path("world.dzgeo");
        let file = fs::File::create(&path).expect("create capture");
        let mut writer = CaptureWriter::new(file, &params).expect("capture header");
        for tile in &tiles {
            writer.add(tile).expect("capture tile");
        }
        path
    }

    /// A `.nm` of the whole synthetic world, generated by the CLI.
    fn nm(&self) -> PathBuf {
        let cap = self.capture();
        let nm = self.path("out.nm");
        let out = self.run(&[
            "navmesh",
            "generate",
            "--capture",
            s(&cap),
            "--threads",
            "2",
            s(&nm),
        ]);
        assert_eq!(out.code, 0, "{}", out.stderr);
        nm
    }
}

fn s(p: &Path) -> &str {
    p.to_str().expect("utf-8 path")
}

fn server() -> (FakeServer, String) {
    let (params, tiles) = synthetic_world();
    let server = FakeServer::start(params, tiles, Faults::none());
    let addr = server.addr().to_string();
    (server, addr)
}

#[test]
fn probe_prints_world() {
    let env = Env::new();
    let (_server, addr) = server();
    let out = env.run(&["navmesh", "probe", "--server", &addr]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    assert!(
        out.stdout
            .contains("world 150.0 x 150.0 m, tiles 3 x 3 of 50.0 x 50.0 m"),
        "{}",
        out.stdout
    );
    assert!(
        out.stdout
            .contains("cell class 1: 500 cells over 50.00 m (cs 0.100)"),
        "{}",
        out.stdout
    );
    assert!(out.stdout.contains("link 0: typeId -1"), "{}", out.stdout);
}

