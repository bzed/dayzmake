#[test]
fn generate_from_server_range_records_and_resumes() {
    let env = Env::new();
    let (_server, addr) = server();
    let nm = env.path("part.nm");
    let rec = env.path("rec.dzgeo");
    let out = env.run(&[
        "navmesh",
        "generate",
        "--server",
        &addr,
        "--range",
        "0,0,2,0",
        "--threads",
        "2",
        "--record",
        s(&rec),
        s(&nm),
    ]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    assert!(out.stdout.contains("built 3 tiles"), "{}", out.stdout);
    assert!(rec.is_file());
    // resume over the whole world: only the six missing tiles are built
    let full = env.path("full.nm");
    fs::copy(&nm, &full).expect("copy");
    let out = env.run(&[
        "navmesh",
        "generate",
        "--server",
        &addr,
        "--base",
        s(&full),
        "--skip-existing",
        "--threads",
        "2",
        "-f",
        s(&full),
    ]);
    assert_eq!(out.code, 0, "{}", out.stderr);
    assert!(out.stdout.contains("built 6 tiles"), "{}", out.stdout);
    // and equals one run over everything
    let direct = env.nm();
    assert_eq!(
        fs::read(&full).expect("read"),
        fs::read(&direct).expect("read")
    );
}

