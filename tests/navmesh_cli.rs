#[test]
fn parsers_accept_and_reject() {
    assert_eq!(parse_range("0,1,2,3").expect("range"), [0, 1, 2, 3]);
    assert_eq!(parse_range(" -1, 0,5,6").expect("range"), [-1, 0, 5, 6]);
    assert!(
        parse_range("1,2,3")
            .expect_err("three numbers")
            .to_string()
            .contains("expected x0,z0,x1,z1")
    );
    assert!(parse_range("a,b,c,d").is_err());
    assert_eq!(parse_seed("1,2.5,-3").expect("seed"), [1.0, 2.5, -3.0]);
    assert!(
        parse_seed("1,2")
            .expect_err("two numbers")
            .to_string()
            .contains("expected x,y,z")
    );
    assert!(parse_seed("1,nan,3").is_err());
    assert_eq!(parse_tile("4,5").expect("tile"), (4, 5));
    assert!(parse_tile("4").is_err());
    assert_eq!(parse_doors("closed").expect("doors"), DoorPolicy::Closed);
    assert_eq!(parse_doors("open").expect("doors"), DoorPolicy::Open);
    assert_eq!(parse_doors("enabled").expect("doors"), DoorPolicy::Enabled);
    assert!(parse_doors("ajar").is_err());
}

#[test]
fn generate_failed_tiles_exit_1_but_save_the_mesh() {
    let env = Env::new();
    let (params, tiles) = synthetic_world();
    let server = FakeServer::start(
        params,
        tiles,
        Faults::always(navmesh_server::Fault::Malformed),
    );
    let addr = server.addr().to_string();
    let nm = env.path("out.nm");
    let out = env.run(&[
        "navmesh",
        "generate",
        "--server",
        &addr,
        "--range",
        "0,0,0,1",
        "--threads",
        "2",
        s(&nm),
    ]);
    assert_eq!(out.code, 1, "{}", out.stdout);
    assert!(out.stdout.contains("2 failed"), "{}", out.stdout);
    assert!(out.stdout.contains("  tile (0,0): "), "{}", out.stdout);
    assert!(out.stdout.contains("wrote "), "{}", out.stdout);
    assert!(out.stderr.contains("could not be built"), "{}", out.stderr);
    assert!(nm.is_file(), "the partial mesh is saved");
}

